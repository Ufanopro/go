package main

import "fmt"

func main() {
	// Declaración de variables
	var numero int = 25               // Variable de tipo entero (número)
	var texto string = "Go es genial" // Variable de tipo cadena (string)
	var esActivo bool = true          // Variable de tipo booleano

	// Imprimir las variables
	fmt.Println("Número:", numero)
	fmt.Println("Texto:", texto)
	fmt.Println("¿Es activo?", esActivo)
}
